using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
// no runtime dependency on StateMachine here; we only emit code that references it in generated sources

namespace FSMScriptAnalyzer
{
    [Generator]
    public class FSMScriptAnalyzerGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var scripts = context.AdditionalTextsProvider
                .Where(at => at.Path.EndsWith(".FSMScript", StringComparison.OrdinalIgnoreCase))
                .Select((text, ct) => new ScriptInfo(
                    Path.GetFileNameWithoutExtension(text.Path),
                    text.Path,
                    text.GetText(ct)?.ToString() ?? string.Empty));

            var filtered = scripts.Where(s => !string.IsNullOrWhiteSpace(s.Content));

            var fsmModuleIndex = context.AdditionalTextsProvider
                .Where(at => at.Path.EndsWith(".fsm", StringComparison.OrdinalIgnoreCase))
                .Select((text, ct) => new ScriptInfo(
                    Path.GetFileNameWithoutExtension(text.Path),
                    Path.GetFullPath(text.Path),
                    text.GetText(ct)?.ToString() ?? string.Empty))
                .Collect()
                .Select((files, _) => files.ToDictionary(
                    file => file.Path,
                    file => file,
                    StringComparer.OrdinalIgnoreCase));

            var compilation = context.CompilationProvider;
            var rootNamespace = context.AnalyzerConfigOptionsProvider
                .Select((opts, _) =>
                {
                    return opts.GlobalOptions.TryGetValue("build_property.RootNamespace", out var ns) ? ns : null;
                });

            var combined = filtered.Combine(compilation).Combine(rootNamespace).Combine(fsmModuleIndex);

            context.RegisterSourceOutput(combined, (spc, triple) =>
            {
                var s = triple.Left.Left.Left;
                var comp = triple.Left.Left.Right;
                var ns = triple.Left.Right;
                var moduleIndex = triple.Right;
                var typeMap = BuildNodeTypeMap(comp);
                var declarations = ScriptDeclarations.Read(s.Content);
                var targetNs = string.IsNullOrWhiteSpace(ns) ? comp.AssemblyName ?? "FSM" : ns!;
                var source = GenerateScriptClassSource(s, declarations.Nodes, declarations.Events, typeMap, targetNs, moduleIndex);
                var hintName = $"{targetNs}.{s.FileName}.g.cs";
                spc.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
            });
        }

        private static string GenerateScriptClassSource(ScriptInfo s, List<NodeDeclaration> nodes, IEnumerable<string> events, Dictionary<string, string> typeMap, string targetNamespace, Dictionary<string, ScriptInfo> moduleIndex)
        {
            var moduleScripts = CollectModuleScripts(s, moduleIndex);

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine($"namespace {targetNamespace}");
            sb.AppendLine("{");
            var className = MakeIdentifier(s.FileName);
            sb.AppendLine($"    public class {className}");
            sb.AppendLine("    {");
            sb.AppendLine($"        public static string ScriptText => @\"{EscapeForVerbatimString(s.Content)}\";");
            sb.AppendLine();

            if (moduleScripts.Length > 0)
            {
                sb.AppendLine("        public static string[] ModuleScripts => new[] {");
                for (int i = 0; i < moduleScripts.Length; i++)
                {
                    var comma = i < moduleScripts.Length - 1 ? "," : "";
                    sb.AppendLine($"            @\"{EscapeForVerbatimString(moduleScripts[i].Value)}\"{comma}");
                }
                sb.AppendLine("        };");
            }
            else
            {
                sb.AppendLine("        public static string[] ModuleScripts => new string[] { };");
            }
            sb.AppendLine();

            sb.AppendLine($"        public static {className} Create(global::StateMachine.IFSMNodeFactory factory)");
            sb.AppendLine("        {");
            sb.AppendLine($"            return new {className}(factory);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        private {className}() {{ }}");
            sb.AppendLine();
            sb.AppendLine("        public global::StateMachine.FSMEngine Engine { get; }");
            sb.AppendLine();
            sb.AppendLine($"        public {className}(global::StateMachine.IFSMNodeFactory factory)");
            sb.AppendLine("        {");
            sb.AppendLine("            Engine = new global::StateMachine.FSMEngine(factory);");
            if (moduleScripts.Length > 0)
            {
                sb.AppendLine("            var moduleScripts = ModuleScripts;");
                for (var i = 0; i < moduleScripts.Length; i++)
                    sb.AppendLine($"            Engine.RegisterModule(\"{moduleScripts[i].Key}\", moduleScripts[{i}]);");
            }
            sb.AppendLine("            Engine.CreateStateMachine(ScriptText);");
            sb.AppendLine("        }");
            sb.AppendLine();
            foreach (var n in nodes)
            {
                var propName = MakeIdentifier(n.Name);
                sb.AppendLine();
                typeMap.TryGetValue(n.TypeKey, out var typeFullName);
                typeFullName ??= "global::StateMachine.IFSMNode";
                sb.AppendLine($"        public {typeFullName} {propName} => Engine.GetNode<{typeFullName}>(\"{n.Name}\");");
            }
            foreach (var ev in events.Distinct(StringComparer.Ordinal))
            {
                var propName = MakeIdentifier(ev);
                sb.AppendLine();
                sb.AppendLine($"        public global::StateMachine.FSMEvent {propName} => Engine.GetEvent(\"{ev}\");");
            }
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static KeyValuePair<string, string>[] CollectModuleScripts(ScriptInfo script, Dictionary<string, ScriptInfo> moduleIndex)
        {
            var result = new List<KeyValuePair<string, string>>();
            var visited = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            CollectRecursive(script, moduleIndex, visited, result);
            return result.ToArray();
        }

        private static void CollectRecursive(ScriptInfo script, Dictionary<string, ScriptInfo> moduleIndex, HashSet<string> visited, List<KeyValuePair<string, string>> result)
        {
            var imports = ScriptDeclarations.Read(script.Content).Imports;
            foreach (var import in imports)
            {
                if (!visited.Add(import)) continue;
                // Match Engine's relative-file lookup; unrelated AdditionalFiles with the
                // same basename must not replace a dependency of this script.
                var path = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(script.Path) ?? ".", import + ".fsm"));
                if (moduleIndex.TryGetValue(path, out var module))
                {
                    // Register by import identity, not a regex match on the module header:
                    // files may have aliases, comments, or no module wrapper at all.
                    result.Add(new KeyValuePair<string, string>(import, module.Content));
                    CollectRecursive(module, moduleIndex, visited, result);
                }
            }
        }

        private static string EscapeForVerbatimString(string input)
        {
            return input.Replace("\"", "\"\"");
        }

        private static string MakeIdentifier(string raw)
        {
            if (string.IsNullOrWhiteSpace(raw)) return "FSM_Script";
            var s = new string(raw.Select(ch => char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_').ToArray());
            if (!Microsoft.CodeAnalysis.CSharp.SyntaxFacts.IsValidIdentifier(s)) s = "FSM_Script";
            return s;
        }

        private readonly struct ScriptInfo : IEquatable<ScriptInfo>
        {
            public string FileName { get; }
            public string Path { get; }
            public string Content { get; }

            public ScriptInfo(string fileName, string path, string content)
            {
                FileName = fileName ?? string.Empty;
                Path = path ?? string.Empty;
                Content = content ?? string.Empty;
            }

            public bool Equals(ScriptInfo other)
            {
                return string.Equals(Path, other.Path, StringComparison.OrdinalIgnoreCase)
                    && string.Equals(Content, other.Content, StringComparison.Ordinal);
            }

            public override bool Equals(object? obj)
            {
                return obj is ScriptInfo other && Equals(other);
            }

            public override int GetHashCode()
            {
                unchecked
                {
                    var h1 = StringComparer.OrdinalIgnoreCase.GetHashCode(Path);
                    var h2 = StringComparer.Ordinal.GetHashCode(Content);
                    return (h1 * 397) ^ h2;
                }
            }
        }

        private static Dictionary<string, string> BuildNodeTypeMap(Compilation compilation)
        {
            var result = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            var attr = compilation.GetTypeByMetadataName("StateMachine.FSMNodeAttribute");
            if (attr == null) return result;

            void Traverse(INamespaceSymbol ns)
            {
                foreach (var m in ns.GetMembers())
                {
                    if (m is INamespaceSymbol childNs)
                    {
                        Traverse(childNs);
                    }
                    else if (m is INamedTypeSymbol type)
                    {
                        foreach (var a in type.GetAttributes())
                        {
                            if (!SymbolEqualityComparer.Default.Equals(a.AttributeClass, attr)) continue;
                            string? key = null;
                            if (a.ConstructorArguments.Length > 0)
                            {
                                var arg = a.ConstructorArguments[0];
                                if (arg.Kind == TypedConstantKind.Primitive && arg.Value is string s) key = s;
                            }
                            if (key is null)
                            {
                                foreach (var na in a.NamedArguments)
                                {
                                    if (na.Key == "Key" && na.Value.Kind == TypedConstantKind.Primitive && na.Value.Value is string ks)
                                    {
                                        key = ks;
                                        break;
                                    }
                                }
                            }
                            if (key != null && !string.IsNullOrWhiteSpace(key))
                            {
                                var fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                                if (!result.ContainsKey(key)) result[key] = fullName;
                            }
                        }
                    }
                }
            }
            Traverse(compilation.GlobalNamespace);
            return result;
        }

    }
}
